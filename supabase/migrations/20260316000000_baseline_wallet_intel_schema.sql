        p_token_mint,
        p_token_symbol,
        v_action,
        p_amount_sol,
        p_amount_token,
        p_price_per_token,
        p_wallet_address || ':' || p_signature,
        jsonb_build_object(
            'ingest_function', 'wallet_intel.ingest_wallet_trade_event',
            'version', 'v2.0'
        )
    )
    on conflict (wallet_address, signature)
    where event_source = 'wallet_trade'
      and wallet_address is not null
      and signature is not null
