-- ---- system_health_check ----
CREATE OR REPLACE FUNCTION wallet_intel.system_health_check()
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE
  v_ingestor_lag    numeric;
  v_signals_24h     int;
  v_scoring_lag     numeric;
  v_tco_24h         int;
  v_tier0           int;
  v_tier1           int;
  v_status          text := 'healthy';
  v_alerts          text[] := '{}';
  v_last_score      timestamptz;
  v_last_trade      timestamptz;
BEGIN

  -- 1. Ingestor lag (hours since last wallet trade)
  SELECT MAX(occurred_at) INTO v_last_trade
  FROM wallet_intel.wallet_trade_events;

  v_ingestor_lag := ROUND(EXTRACT(EPOCH FROM (NOW() - v_last_trade))/3600, 2);

  IF v_ingestor_lag > 2 THEN
    v_alerts := array_append(v_alerts, FORMAT('INGESTOR LAG: %s hours since last trade', v_ingestor_lag));
    v_status := 'degraded';
  END IF;
  IF v_ingestor_lag > 6 THEN
    v_status := 'critical';
  END IF;

  -- 2. Signal detector health (signals in last 24h)
  SELECT COUNT(*) INTO v_signals_24h
  FROM wallet_ops.execution_signals
  WHERE generated_at >= NOW() - INTERVAL '24 hours';

  IF v_signals_24h = 0 THEN
    v_alerts := array_append(v_alerts, 'NO SIGNALS in last 24 hours â detector may be stuck');
    v_status := CASE WHEN v_status = 'critical' THEN 'critical' ELSE 'degraded' END;
  END IF;

  -- 3. Scoring freshness
  SELECT MAX(scored_at) INTO v_last_score
  FROM wallet_intel.wallet_score_history;

  v_scoring_lag := ROUND(EXTRACT(EPOCH FROM (NOW() - v_last_score))/3600, 2);

  IF v_scoring_lag > 5 THEN
    v_alerts := array_append(v_alerts, FORMAT('SCORING STALE: last run %s hours ago', v_scoring_lag));
    v_status := CASE WHEN v_status = 'critical' THEN 'critical' ELSE 'degraded' END;
  END IF;

  -- 4. Telegram call outcomes freshness (last 24h)
  SELECT COUNT(*) INTO v_tco_24h
  FROM wallet_intel.telegram_call_outcomes
  WHERE message_timestamp >= NOW() - INTERVAL '24 hours';

  IF v_tco_24h = 0 THEN
    v_alerts := array_append(v_alerts, 'NO TELEGRAM OUTCOMES logged in 24h â outcome ingestor may be down');
    v_status := CASE WHEN v_status = 'critical' THEN 'critical' ELSE 'degraded' END;
  END IF;

  -- 5. Tier counts (check for tier collapse)
  SELECT COUNT(*) INTO v_tier0 FROM public.tracked_wallets WHERE wallet_tier = 'tier_0';
  SELECT COUNT(*) INTO v_tier1 FROM public.tracked_wallets WHERE wallet_tier = 'tier_1';

  IF v_tier0 = 0 THEN
    v_alerts := array_append(v_alerts, 'CRITICAL: No Tier-0 wallets â scoring may have collapsed');
    v_status := 'critical';
  END IF;

  -- Log result
  INSERT INTO wallet_intel.system_health_log (
    checked_at, ingestor_status, ingestor_lag_hours,
    signals_last_24h, scoring_last_run, scoring_lag_hours,
    tco_last_24h, tier0_count, tier1_count,
    overall_status, alerts
  ) VALUES (
    NOW(),
    CASE WHEN v_ingestor_lag <= 2 THEN 'ok' WHEN v_ingestor_lag <= 6 THEN 'lagging' ELSE 'down' END,
    v_ingestor_lag,
    v_signals_24h,
    v_last_score,
    v_scoring_lag,
    v_tco_24h,
    v_tier0,
    v_tier1,
    v_status,
    v_alerts
  );

  RETURN FORMAT(
    'status:%s | ingestor_lag:%sh | signals_24h:%s | scoring_lag:%sh | tco_24h:%s | tier0:%s | tier1:%s | alerts:%s',
    v_status, v_ingestor_lag, v_signals_24h, v_scoring_lag, v_tco_24h, v_tier0, v_tier1,
    CASE WHEN array_length(v_alerts,1) IS NULL THEN 'none' ELSE array_to_string(v_alerts,' | ') END
  );
END;
$function$

-- ---- update_wallet_position ----
CREATE OR REPLACE FUNCTION wallet_intel.update_wallet_position(p_wallet_address text, p_token_address text)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    total_bought DECIMAL;
    total_sold DECIMAL;
    avg_buy_price DECIMAL;
    avg_sell_price DECIMAL;
    first_buy TIMESTAMPTZ;
    last_buy TIMESTAMPTZ;
    first_sell TIMESTAMPTZ;
    last_sell TIMESTAMPTZ;
    buy_count INTEGER;
    sell_count INTEGER;
    total_cost DECIMAL;
    total_revenue DECIMAL;
BEGIN
    -- Aggregate buy data
    SELECT 
        COALESCE(SUM(amount_tokens), 0),
        COALESCE(AVG(price_per_token), 0),
        MIN(block_time),
        MAX(block_time),
        COUNT(*),
        COALESCE(SUM(amount_sol), 0)
    INTO total_bought, avg_buy_price, first_buy, last_buy, buy_count, total_cost
    FROM wallet_intel.wallet_trades
    WHERE wallet_address = p_wallet_address
        AND token_address = p_token_address
        AND action = 'buy';
    
    -- Aggregate sell data
    SELECT 
        COALESCE(SUM(amount_tokens), 0),
        COALESCE(AVG(price_per_token), 0),
        MIN(block_time),
        MAX(block_time),
        COUNT(*),
        COALESCE(SUM(amount_sol), 0)
    INTO total_sold, avg_sell_price, first_sell, last_sell, sell_count, total_revenue
    FROM wallet_intel.wallet_trades
    WHERE wallet_address = p_wallet_address
        AND token_address = p_token_address
        AND action = 'sell';
    
    -- Insert or update position
    INSERT INTO wallet_intel.wallet_token_positions (
        wallet_address,
        token_address,
        current_balance,
        avg_entry_price,
        total_cost_sol,
        first_buy_at,
        last_buy_at,
        buy_count,
        total_bought,
        first_sell_at,
        last_sell_at,
        sell_count,
        total_sold,
        realized_pnl_sol,
        realized_pnl_percent,
        hold_time_minutes,
        is_closed
    ) VALUES (
        p_wallet_address,
        p_token_address,
        total_bought - total_sold,
        avg_buy_price,
        total_cost,
        first_buy,
        last_buy,
        buy_count,
        total_bought,
        first_sell,
        last_sell,
        sell_count,
        total_sold,
        total_revenue - total_cost,
        CASE WHEN total_cost > 0 THEN ((total_revenue - total_cost) / total_cost * 100) ELSE 0 END,
        CASE WHEN first_buy IS NOT NULL AND last_sell IS NOT NULL 
            THEN EXTRACT(EPOCH FROM (last_sell - first_buy)) / 60 
            ELSE NULL END,
        (total_bought - total_sold) < 0.000001 -- Effectively closed
    )
    ON CONFLICT (wallet_address, token_address)
    DO UPDATE SET
        current_balance = EXCLUDED.current_balance,
        avg_entry_price = EXCLUDED.avg_entry_price,
        total_cost_sol = EXCLUDED.total_cost_sol,
        last_buy_at = EXCLUDED.last_buy_at,
        buy_count = EXCLUDED.buy_count,
        total_bought = EXCLUDED.total_bought,
        first_sell_at = COALESCE(wallet_intel.wallet_token_positions.first_sell_at, EXCLUDED.first_sell_at),
        last_sell_at = EXCLUDED.last_sell_at,
        sell_count = EXCLUDED.sell_count,
        total_sold = EXCLUDED.total_sold,
        realized_pnl_sol = EXCLUDED.realized_pnl_sol,
        realized_pnl_percent = EXCLUDED.realized_pnl_percent,
        hold_time_minutes = EXCLUDED.hold_time_minutes,
        is_closed = EXCLUDED.is_closed,
        updated_at = NOW();
END;
$function$

-- ---- validate_data_quality ----
CREATE OR REPLACE FUNCTION wallet_intel.validate_data_quality()
 RETURNS TABLE(check_name text, status text, details text)
 LANGUAGE plpgsql
AS $function$
BEGIN
    -- Check 1: Orphaned trades (no position)
    RETURN QUERY
    SELECT 
        'orphaned_trades'::TEXT,
        CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END::TEXT,
        'Trades without corresponding positions: ' || COUNT(*)::TEXT
    FROM wallet_intel.wallet_trades wt
    WHERE NOT EXISTS (
        SELECT 1 FROM wallet_intel.wallet_token_positions wtp
        WHERE wtp.wallet_address = wt.wallet_address
            AND wtp.token_address = wt.token_address
    );
    
    -- Check 2: Negative balances
    RETURN QUERY
    SELECT 
        'negative_balances'::TEXT,
        CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'WARN' END::TEXT,
        'Positions with negative balance: ' || COUNT(*)::TEXT
    FROM wallet_intel.wallet_token_positions
    WHERE current_balance < 0 AND NOT is_closed;
    
    -- Check 3: Missing timestamps
    RETURN QUERY
    SELECT 
        'missing_timestamps'::TEXT,
        CASE WHEN COUNT(*) = 0 THEN 'PASS' ELSE 'FAIL' END::TEXT,
        'Trades without block_time: ' || COUNT(*)::TEXT
    FROM wallet_intel.wallet_trades
    WHERE block_time IS NULL;
    
    -- Check 4: Stale market snapshots
    RETURN QUERY
    SELECT 
        'stale_snapshots'::TEXT,
        CASE WHEN MAX(snapshot_time) > NOW() - INTERVAL '15 minutes' THEN 'PASS' ELSE 'WARN' END::TEXT,
        'Last snapshot: ' || COALESCE(MAX(snapshot_time)::TEXT, 'never')
    FROM wallet_intel.token_market_snapshots;
    
    -- Check 5: Materialized view freshness
    RETURN QUERY
    SELECT 
        'mv_freshness'::TEXT,
        CASE WHEN MAX(last_updated) > NOW() - INTERVAL '20 minutes' THEN 'PASS' ELSE 'WARN' END::TEXT,
        'Last MV refresh: ' || COALESCE(MAX(last_updated)::TEXT, 'never')
    FROM wallet_intel.mv_hot_streak_leaderboard;
    
END;
$function$


