-- ---- rescore_wallets ----
CREATE OR REPLACE FUNCTION wallet_intel.rescore_wallets()
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE v_result text := '';
BEGIN

  -- Step 1: Daily stats upsert (last 7 days)
  INSERT INTO wallet_intel.wallet_daily_stats (
    wallet_address, stats_date,
    total_trades, buy_count, sell_count, volume_sol,
    realized_pnl_sol, unrealized_pnl_sol,
    winning_trades, losing_trades, win_rate,
    median_return_percent, average_return_percent,
    profit_factor, expectancy_per_trade,
    max_drawdown_percent, average_hold_time_minutes,
    average_time_to_peak_minutes, total_slippage_sol,
    total_fees_sol, illiquid_trap_count
  )
  SELECT
    wallet_address, DATE(occurred_at),
    COUNT(*), COUNT(*) FILTER (WHERE action='buy'), COUNT(*) FILTER (WHERE action='sell'),
    ROUND(SUM(amount_sol)::numeric,6),
    ROUND((COALESCE(SUM(amount_sol) FILTER (WHERE action='sell'),0) - COALESCE(SUM(amount_sol) FILTER (WHERE action='buy'),0))::numeric,6),
    0,
    CASE WHEN COALESCE(SUM(amount_sol) FILTER (WHERE action='sell'),0) > COALESCE(SUM(amount_sol) FILTER (WHERE action='buy'),0) THEN 1 ELSE 0 END,
    CASE WHEN COALESCE(SUM(amount_sol) FILTER (WHERE action='sell'),0) <= COALESCE(SUM(amount_sol) FILTER (WHERE action='buy'),0) AND COUNT(*) FILTER (WHERE action='sell') > 0 THEN 1 ELSE 0 END,
    ROUND(CASE WHEN COUNT(*)>0 THEN COUNT(*) FILTER (WHERE action='sell')::numeric/COUNT(*)::numeric ELSE 0 END,4),
    ROUND(COALESCE(AVG(amount_sol),0)::numeric,6),
    ROUND(COALESCE(AVG(amount_sol),0)::numeric,6),
    CASE WHEN COALESCE(SUM(amount_sol) FILTER (WHERE action='buy'),0)=0 THEN NULL
         ELSE ROUND(COALESCE(SUM(amount_sol) FILTER (WHERE action='sell'),0)::numeric / SUM(amount_sol) FILTER (WHERE action='buy')::numeric,4) END,
    ROUND(COALESCE(AVG(amount_sol),0)::numeric,6),
    0, NULL, NULL, 0, ROUND((COUNT(*)*0.000005)::numeric,6), 0
  FROM wallet_intel.wallet_trade_events
  WHERE occurred_at >= CURRENT_DATE - 7
  GROUP BY wallet_address, DATE(occurred_at)
  ON CONFLICT (wallet_address, stats_date) DO UPDATE SET
    total_trades     = EXCLUDED.total_trades,
    buy_count        = EXCLUDED.buy_count,
    sell_count       = EXCLUDED.sell_count,
    volume_sol       = EXCLUDED.volume_sol,
    realized_pnl_sol = EXCLUDED.realized_pnl_sol,
    winning_trades   = EXCLUDED.winning_trades,
    losing_trades    = EXCLUDED.losing_trades,
    win_rate         = EXCLUDED.win_rate,
    profit_factor    = EXCLUDED.profit_factor;

  v_result := v_result || 'daily_stats:ok | ';

  -- Step 2: Rolling stats â full refresh from daily_stats
  DELETE FROM wallet_intel.wallet_rolling_stats;

  INSERT INTO wallet_intel.wallet_rolling_stats (
    wallet_address, window_period, calculated_at,
    total_trades, realized_pnl_sol, win_rate,
    profit_factor, expectancy, sharpe_like_score,
    winning_streak, losing_streak,
    drawdown_current, drawdown_max,
    early_hit_rate, early_false_positive_rate, edge_decay_score
  )
  WITH windows AS (
    SELECT unnest(ARRAY['7d','30d','90d']) AS wp, unnest(ARRAY[7,30,90]) AS days
  )
  SELECT
    d.wallet_address, w.wp, NOW(),
    SUM(d.total_trades),
    ROUND(SUM(d.realized_pnl_sol)::numeric,6),
    ROUND(AVG(d.win_rate)::numeric,4),
    ROUND(COALESCE(AVG(d.profit_factor),0)::numeric,4),
    ROUND(COALESCE(AVG(d.expectancy_per_trade),0)::numeric,6),
    ROUND(CASE
      WHEN STDDEV(d.realized_pnl_sol) IS NULL OR STDDEV(d.realized_pnl_sol) = 0 THEN 0
      WHEN AVG(d.realized_pnl_sol) IS NULL THEN 0
      ELSE AVG(d.realized_pnl_sol) / NULLIF(STDDEV(d.realized_pnl_sol), 0)
    END::numeric,4),
    MAX(d.winning_trades), MAX(d.losing_trades),
    0,
    ROUND(MIN(d.realized_pnl_sol)::numeric,6),
    0, 0,
    ROUND(CASE
      WHEN w.wp = '7d' THEN 0
      WHEN AVG(d.realized_pnl_sol) IS NULL OR ABS(AVG(d.realized_pnl_sol)) < 0.001 THEN 0
      ELSE (COALESCE(SUM(d.realized_pnl_sol) FILTER (WHERE d.stats_date >= CURRENT_DATE-7), 0) - AVG(d.realized_pnl_sol))
           / ABS(AVG(d.realized_pnl_sol))
    END::numeric,4)
  FROM wallet_intel.wallet_daily_stats d
  CROSS JOIN windows w
  WHERE d.stats_date >= CURRENT_DATE - w.days
  GROUP BY d.wallet_address, w.wp, w.days
  ON CONFLICT DO NOTHING;

  v_result := v_result || 'rolling_stats:ok | ';

  -- Step 3: Alpha stats â update PnL from rolling, trade counts from events
  UPDATE wallet_intel.wallet_alpha_stats was
  SET
    pnl_7d         = COALESCE(r7.realized_pnl_sol,  was.pnl_7d),
    pnl_30d        = COALESCE(r30.realized_pnl_sol, was.pnl_30d),
    pnl_90d        = COALESCE(r90.realized_pnl_sol, was.pnl_90d),
    win_rate_90d   = COALESCE(r90.win_rate,          was.win_rate_90d),
    sharpe_90d     = COALESCE(r90.sharpe_like_score, was.sharpe_90d),
    edge_decay_90d = COALESCE(r90.edge_decay_score,  was.edge_decay_90d),
    total_buys     = COALESCE(tt.total_buys,         was.total_buys),
    unique_tokens  = COALESCE(tt.unique_tokens,      was.unique_tokens),
    bayes_weight   = ROUND((COALESCE(tt.total_buys, was.total_buys)::numeric / (COALESCE(tt.total_buys, was.total_buys) + 50))::numeric,4),
    computed_at    = NOW()
  FROM (
    SELECT wallet_address,
      COUNT(*) FILTER (WHERE action='buy') AS total_buys,
      COUNT(DISTINCT token_mint) AS unique_tokens
    FROM wallet_intel.wallet_trade_events
    WHERE occurred_at >= CURRENT_DATE - 90
    GROUP BY wallet_address
  ) tt
  LEFT JOIN wallet_intel.wallet_rolling_stats r90 ON r90.wallet_address = tt.wallet_address AND r90.window_period = '90d'
  LEFT JOIN wallet_intel.wallet_rolling_stats r30 ON r30.wallet_address = tt.wallet_address AND r30.window_period = '30d'
  LEFT JOIN wallet_intel.wallet_rolling_stats r7  ON r7.wallet_address  = tt.wallet_address AND r7.window_period  = '7d'
  WHERE was.wallet_address = tt.wallet_address;

  v_result := v_result || 'alpha_stats:ok | ';

  -- Step 4: New score snapshot
  INSERT INTO wallet_intel.wallet_score_history (
    wallet_address, scored_at,
    performance_score, earliness_score, predictive_score,
    consistency_score, trust_score, copyability_score,
    hot_streak_score, telegram_confluence_score,
    cohort_leadership_score, exit_timing_score,
    overall_rank, category_ranks, sample_size, confidence_interval
  )
  WITH percentiles AS (
    SELECT *,
      ROUND(PERCENT_RANK() OVER (ORDER BY pnl_90d*0.2+pnl_30d*0.3+pnl_7d*0.5)*100)::numeric AS perf_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY
        (pre_alert_hits::numeric/NULLIF(unique_tokens,0))*0.40
        +(pre_alert_10x::numeric/NULLIF(unique_tokens,0))*0.40
        +LEAST(avg_lead_minutes/120.0,1.0)*0.20
      )*100)::numeric AS early_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY early_hit_rate_90d)*100)::numeric AS predict_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY win_rate_90d-GREATEST(edge_decay_90d,0))*100)::numeric AS consist_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY bayes_weight)*100)::numeric AS trust_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY copyability_score)*100)::numeric AS copy_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY pnl_7d-(pnl_30d/4.0))*100)::numeric AS streak_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY tg_anticipation)*100)::numeric AS tg_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY leadership_ratio*0.5+cluster_success*0.5)*100)::numeric AS leader_pct,
      ROUND(PERCENT_RANK() OVER (ORDER BY exit_timing_quality)*100)::numeric AS exit_pct
    FROM wallet_intel.wallet_alpha_stats
  ),
  final AS (
    SELECT *,
      ROUND((early_pct*0.30+perf_pct*0.25+consist_pct*0.20+copy_pct*0.15+leader_pct*0.07+trust_pct*0.03)*bayes_weight)::numeric AS composite
    FROM percentiles
  )
  SELECT
    wallet_address, NOW(),
    perf_pct, early_pct, predict_pct, consist_pct, trust_pct, copy_pct,
    streak_pct, tg_pct, leader_pct, exit_pct,
    RANK() OVER (ORDER BY composite DESC)::int,
    jsonb_build_object('performance',perf_pct,'earliness',early_pct,'consistency',consist_pct,'copy_safety',copy_pct,'leadership',leader_pct,'composite',composite),
    total_buys, bayes_weight
  FROM final
  ON CONFLICT DO NOTHING;

  v_result := v_result || 'score_history:ok | ';

  -- Step 5: Update tracked_wallets tiers
  UPDATE public.tracked_wallets tw
  SET
    priority_score   = latest.composite,
    confidence_score = latest.confidence_interval,
    wallet_tier      = CASE
      WHEN latest.overall_rank <= 10  THEN 'tier_0'
      WHEN latest.overall_rank <= 100 THEN 'tier_1'
      WHEN latest.overall_rank <= 250 THEN 'tier_2'
      WHEN latest.overall_rank <= 500 THEN 'tier_3'
      ELSE 'tier_4'
    END,
    updated_at = NOW()
  FROM (
    SELECT DISTINCT ON (wallet_address)
      wallet_address, overall_rank, confidence_interval,
      (category_ranks->>'composite')::numeric AS composite
    FROM wallet_intel.wallet_score_history
    ORDER BY wallet_address, scored_at DESC
  ) latest
  WHERE tw.wallet_address = latest.wallet_address;

  v_result := v_result || 'tracked_wallets:ok';
  RETURN v_result;
END;
$function$

