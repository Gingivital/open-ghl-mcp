CREATE OR REPLACE VIEW wallet_intel.wallet_leaderboard AS
    SELECT wallet_address,
           0 AS total_trades, 0 AS realized_pnl_sol, 0 AS win_rate,
           0 AS profit_factor, 0 AS expectancy, 0 AS sharpe_like_score,
           0 AS winning_streak, 0 AS rank_score
    FROM tracked_wallets
    LIMIT 10;
