    end if;

    if p_token_mint is null or length(trim(p_token_mint)) = 0 then
        raise exception 'p_token_mint is required';
    end if;

    if p_action not in ('buy', 'sell') then
        raise exception 'p_action must be buy or sell, got: %', p_action;
    end if;

    v_action := p_action::wallet_intel.trade_action;

    insert into wallet_intel.events (
        event_source,
