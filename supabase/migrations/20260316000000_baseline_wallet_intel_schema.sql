-- ---- detect_exit_warning ----
CREATE OR REPLACE FUNCTION wallet_intel.detect_exit_warning(p_lookback_minutes integer DEFAULT 15, p_min_sellers integer DEFAULT 2)
 RETURNS TABLE(token_address text, token_symbol text, seller_count integer, avg_seller_hot_score numeric, total_sold_sol numeric, signal_strength text, action_recommendation text)
 LANGUAGE plpgsql
