CREATE TABLE IF NOT EXISTS wallet_intel.events (
    id              bigint          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    event_source    wallet_intel.event_source NOT NULL,
    event_type      text            NOT NULL,
    signature       text,
    wallet_address  text,
    occurred_at     timestamptz     NOT NULL,
    ingested_at     timestamptz     NOT NULL DEFAULT now(),
    token_mint      text,
    token_symbol    text,
    action          wallet_intel.trade_action,
    amount_sol      numeric,
    amount_token    numeric,
    price_per_token numeric,
    dedupe_key      text,
    source_ref      text,
    metadata        jsonb           NOT NULL DEFAULT '{}'::jsonb,
    created_at      timestamptz     NOT NULL DEFAULT now(),
    CONSTRAINT events_pkey PRIMARY KEY (id),
    CONSTRAINT events_event_type_not_blank
        CHECK (length(TRIM(BOTH FROM event_type)) > 0),
    CONSTRAINT events_amounts_nonnegative
        CHECK (
            (amount_sol IS NULL OR amount_sol >= 0) AND
            (amount_token IS NULL OR amount_token >= 0) AND
            (price_per_token IS NULL OR price_per_token >= 0)
        ),
    CONSTRAINT events_wallet_trade_required_fields
        CHECK (
            event_source <> 'wallet_trade'::wallet_intel.event_source OR (
                signature IS NOT NULL AND wallet_address IS NOT NULL AND
                token_mint IS NOT NULL AND action IS NOT NULL
            )
        )
);

