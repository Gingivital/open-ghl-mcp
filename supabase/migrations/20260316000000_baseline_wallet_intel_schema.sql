            wt.token_address,
            wt.token_symbol,
            wt.wallet_address,
            wt.amount_sol,
            (SELECT score FROM wallet_intel.calculate_hot_streak_score(wt.wallet_address, 3)) as hot_score
        FROM wallet_intel.wallet_trades wt
        WHERE wt.action = 'sell'
            AND wt.block_time > NOW() - (p_lookback_minutes || ' minutes')::INTERVAL
    ),
    exit_stats AS (
        SELECT 
            re.token_address,
            re.token_symbol,
            COUNT(DISTINCT re.wallet_address) as seller_cnt,
            AVG(re.hot_score) as avg_hot,
            SUM(re.amount_sol) as total_sold
        FROM recent_exits re
        WHERE re.hot_score >= 50 -- Only count hot wallets
        GROUP BY re.token_address, re.token_symbol
        HAVING COUNT(DISTINCT re.wallet_address) >= p_min_sellers
    )
    SELECT 
        es.token_address,
        es.token_symbol,
        es.seller_cnt,
        es.avg_hot,
        es.total_sold,
        CASE 
            WHEN es.seller_cnt >= 4 AND es.avg_hot >= 70 THEN 'STRONG'
            WHEN es.seller_cnt >= 3 AND es.avg_hot >= 60 THEN 'MEDIUM'
            ELSE 'WEAK'
        END as signal_strength,
        CASE 
            WHEN es.seller_cnt >= 4 AND es.avg_hot >= 70 THEN 'SELL_NOW'
            WHEN es.seller_cnt >= 3 THEN 'REDUCE_POSITION'
            ELSE 'MONITOR'
        END as action_recommendation
    FROM exit_stats es
    ORDER BY (es.seller_cnt * es.avg_hot) DESC;
END;
$function$

-- ---- detect_hot_wallet_entry ----
CREATE OR REPLACE FUNCTION wallet_intel.detect_hot_wallet_entry()
 RETURNS TABLE(signal_id bigint, wallet_address text, token_address text, token_symbol text, hot_streak_score numeric, trust_score numeric, entry_price numeric, liquidity_usd numeric, signal_strength text, action_recommendation text)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH recent_entries AS (
        -- Trades from last 10 minutes
        SELECT 
            wt.id as trade_id,
            wt.wallet_address,
            wt.token_address,
            wt.token_symbol,
            wt.price_per_token,
            wt.token_liquidity_at_trade,
            wt.percentile_earliness,
            wt.block_time
        FROM wallet_intel.wallet_trades wt
        WHERE wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time > NOW() - INTERVAL '10 minutes'
    ),
    wallet_metrics AS (
        SELECT 
            re.trade_id,
            re.wallet_address,
            re.token_address,
            re.token_symbol,
            re.price_per_token,
            re.token_liquidity_at_trade,
            re.percentile_earliness,
            (SELECT score FROM wallet_intel.calculate_hot_streak_score(re.wallet_address, 3)) as hot_score,
            (SELECT score FROM wallet_intel.calculate_trust_score(re.wallet_address, 30)) as trust_score,
            (SELECT copyability_score FROM wallet_intel.wallet_behavior_profiles WHERE wallet_address = re.wallet_address) as copyability
        FROM recent_entries re
    )
    SELECT 
        wm.trade_id,
        wm.wallet_address,
        wm.token_address,
        wm.token_symbol,
        wm.hot_score,
        wm.trust_score,
        wm.price_per_token,
        wm.token_liquidity_at_trade,
        CASE 
            WHEN wm.hot_score >= 80 AND wm.trust_score >= 70 THEN 'STRONG'
            WHEN wm.hot_score >= 65 AND wm.trust_score >= 60 THEN 'MEDIUM'
            ELSE 'WEAK'
        END as signal_strength,
        CASE 
            WHEN wm.hot_score >= 80 AND wm.trust_score >= 70 AND wm.token_liquidity_at_trade >= 5000 THEN 'BUY_NOW'
            WHEN wm.hot_score >= 65 AND wm.trust_score >= 60 AND wm.token_liquidity_at_trade >= 3000 THEN 'BUY_SMALL'
            WHEN wm.hot_score >= 50 THEN 'WATCH'
            ELSE 'IGNORE'
        END as action_recommendation
    FROM wallet_metrics wm
    WHERE wm.hot_score >= 50
        AND wm.trust_score >= 50
    ORDER BY (wm.hot_score * 0.6 + wm.trust_score * 0.4) DESC;
END;
