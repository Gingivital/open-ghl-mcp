-- ---- ingest_wallet_trade ----
CREATE OR REPLACE FUNCTION wallet_intel.ingest_wallet_trade(p_wallet_address text, p_signature text, p_block_time timestamp with time zone, p_block_slot bigint, p_token_address text, p_token_symbol text, p_token_name text, p_action text, p_amount_tokens numeric, p_amount_sol numeric, p_price_per_token numeric, p_token_mcap numeric DEFAULT NULL::numeric, p_token_liquidity numeric DEFAULT NULL::numeric, p_slippage_percent numeric DEFAULT NULL::numeric, p_fees_paid_sol numeric DEFAULT NULL::numeric)
 RETURNS bigint
 LANGUAGE plpgsql
AS $function$
DECLARE
    new_trade_id BIGINT;
    token_creation_time TIMESTAMPTZ;
    first_liquidity_time TIMESTAMPTZ;
    first_smart_money_time TIMESTAMPTZ;
    wallet_sequence_rank INTEGER;
    earliest_entry_time TIMESTAMPTZ;
BEGIN
    -- Get token lifecycle events
    SELECT event_timestamp INTO token_creation_time
    FROM wallet_intel.token_lifecycle_events
    WHERE token_address = p_token_address
        AND event_type = 'creation'
    LIMIT 1;
    
    SELECT event_timestamp INTO first_liquidity_time
    FROM wallet_intel.token_lifecycle_events
    WHERE token_address = p_token_address
        AND event_type = 'first_liquidity'
    LIMIT 1;
    
    -- Get first smart money entry for this token
    SELECT MIN(block_time) INTO first_smart_money_time
    FROM wallet_intel.wallet_trades
    WHERE token_address = p_token_address
        AND action = 'buy';
    
    -- Calculate sequence rank among wallets for this token
    SELECT COUNT(DISTINCT wallet_address) + 1 INTO wallet_sequence_rank
    FROM wallet_intel.wallet_trades
    WHERE token_address = p_token_address
        AND action = 'buy'
        AND block_time < p_block_time;
    
    -- Get earliest entry time for percentile calculation
    SELECT MIN(block_time) INTO earliest_entry_time
    FROM wallet_intel.wallet_trades
    WHERE token_address = p_token_address
        AND action = 'buy';
    
    -- Insert trade
    INSERT INTO wallet_intel.wallet_trades (
        wallet_address,
        signature,
        block_time,
        block_slot,
        token_address,
        token_symbol,
        token_name,
        action,
        amount_tokens,
        amount_sol,
        price_per_token,
        token_mcap_at_trade,
        token_liquidity_at_trade,
        token_age_seconds,
        seconds_from_token_creation,
        seconds_from_first_liquidity,
        seconds_from_first_smart_money_buy,
        sequence_rank_in_cohort,
        percentile_earliness,
        slippage_percent,
        fees_paid_sol,
        is_first_wallet_entry,
        trade_size_classification
    ) VALUES (
        p_wallet_address,
        p_signature,
        p_block_time,
        p_block_slot,
        p_token_address,
        p_token_symbol,
        p_token_name,
        p_action,
        p_amount_tokens,
        p_amount_sol,
        p_price_per_token,
        p_token_mcap,
        p_token_liquidity,
        CASE WHEN token_creation_time IS NOT NULL 
            THEN EXTRACT(EPOCH FROM (p_block_time - token_creation_time))::INTEGER 
            ELSE NULL END,
        CASE WHEN token_creation_time IS NOT NULL 
            THEN EXTRACT(EPOCH FROM (p_block_time - token_creation_time))::INTEGER 
            ELSE NULL END,
        CASE WHEN first_liquidity_time IS NOT NULL 
            THEN EXTRACT(EPOCH FROM (p_block_time - first_liquidity_time))::INTEGER 
            ELSE NULL END,
        CASE WHEN first_smart_money_time IS NOT NULL 
            THEN EXTRACT(EPOCH FROM (p_block_time - first_smart_money_time))::INTEGER 
            ELSE NULL END,
        wallet_sequence_rank,
        -- Percentile: 0 = earliest, 100 = latest
        CASE WHEN earliest_entry_time IS NOT NULL AND earliest_entry_time < p_block_time
            THEN (EXTRACT(EPOCH FROM (p_block_time - earliest_entry_time)) / 
                  NULLIF(EXTRACT(EPOCH FROM (NOW() - earliest_entry_time)), 0) * 100)
            ELSE 0 
        END,
        p_slippage_percent,
        p_fees_paid_sol,
        -- Is first entry if this wallet hasn't bought this token before
        NOT EXISTS (
            SELECT 1 FROM wallet_intel.wallet_trades 
            WHERE wallet_address = p_wallet_address 
                AND token_address = p_token_address 
                AND action = 'buy'
                AND block_time < p_block_time
        ),
        -- Size classification
        CASE 
            WHEN p_amount_sol < 0.1 THEN 'micro'
            WHEN p_amount_sol < 1.0 THEN 'small'
            WHEN p_amount_sol < 5.0 THEN 'medium'
            WHEN p_amount_sol < 20.0 THEN 'large'
            ELSE 'whale'
        END
    )
    RETURNING id INTO new_trade_id;
    
    -- Update or create position
    PERFORM wallet_intel.update_wallet_position(p_wallet_address, p_token_address);
    
    RETURN new_trade_id;
END;
$function$

