        total_slippage_sol,
        total_fees_sol
    )
    SELECT 
        wallet_address,
        p_stats_date,
        COUNT(*) as total_trades,
        COUNT(*) FILTER (WHERE action = 'buy') as buy_count,
        COUNT(*) FILTER (WHERE action = 'sell') as sell_count,
        SUM(amount_sol) as volume_sol,
        COALESCE(SUM(
            CASE WHEN action = 'sell' 
            THEN amount_sol - (amount_tokens * (
                SELECT AVG(price_per_token) FROM wallet_intel.wallet_trades t2
                WHERE t2.wallet_address = t1.wallet_address
                    AND t2.token_address = t1.token_address
                    AND t2.action = 'buy'
            ))
            ELSE 0 END
        ), 0) as realized_pnl_sol,
        0 as winning_trades, -- Calculated from positions
        0 as losing_trades,
        0 as win_rate,
        0 as median_return_percent,
        0 as average_return_percent,
        0 as profit_factor,
        0 as expectancy_per_trade,
        COALESCE(SUM(slippage_percent * amount_sol / 100), 0) as total_slippage_sol,
        COALESCE(SUM(fees_paid_sol), 0) as total_fees_sol
    FROM wallet_intel.wallet_trades t1
    WHERE block_time::DATE = p_stats_date
    GROUP BY wallet_address
    ON CONFLICT (wallet_address, stats_date)
    DO UPDATE SET
        total_trades = EXCLUDED.total_trades,
        buy_count = EXCLUDED.buy_count,
        sell_count = EXCLUDED.sell_count,
        volume_sol = EXCLUDED.volume_sol,
        realized_pnl_sol = EXCLUDED.realized_pnl_sol;
    
    GET DIAGNOSTICS stats_count = ROW_COUNT;
    RETURN stats_count;
END;
$function$

-- ---- calculate_earliness_score ----
CREATE OR REPLACE FUNCTION wallet_intel.calculate_earliness_score(p_wallet_address text, p_window_days integer DEFAULT 30)
 RETURNS TABLE(score numeric, avg_percentile_earliness numeric, early_winner_rate numeric, avg_seconds_from_creation integer, actionable_earliness_score numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    absolute_earliness_score DECIMAL(10,4);
    relative_earliness_score DECIMAL(10,4);
    outcome_weighted_score DECIMAL(10,4);
    actionability_score DECIMAL(10,4);
    final_score DECIMAL(5,2);
BEGIN
    WITH wallet_entries AS (
        SELECT 
            wt.token_address,
            wt.percentile_earliness,
            wt.seconds_from_token_creation,
            wt.seconds_from_first_smart_money_buy,
            wt.liquidity_depth_percent,
            wtp.realized_pnl_percent,
            CASE WHEN wtp.realized_pnl_percent > 50 THEN 1 ELSE 0 END as is_big_winner
        FROM wallet_intel.wallet_trades wt
        LEFT JOIN wallet_intel.wallet_token_positions wtp 
            ON wt.wallet_address = wtp.wallet_address 
            AND wt.token_address = wtp.token_address
        WHERE wt.wallet_address = p_wallet_address
            AND wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time > NOW() - (p_window_days || ' days')::INTERVAL
    )
    SELECT
        -- Absolute earliness: seconds from creation (normalized)
        100 - LEAST(100, AVG(seconds_from_token_creation) / 600.0 * 100),
        
        -- Relative earliness: percentile among tracked wallets
        100 - AVG(percentile_earliness),
        
        -- Outcome-weighted: how often early entries lead to wins
        AVG(CASE WHEN percentile_earliness < 25 THEN is_big_winner ELSE 0 END) * 100,
        
        -- Actionable earliness: early but still safe to copy
        AVG(CASE 
            WHEN percentile_earliness < 50 AND liquidity_depth_percent < 5 THEN 100
            WHEN percentile_earliness < 50 AND liquidity_depth_percent < 10 THEN 75
            WHEN percentile_earliness < 50 THEN 50
            ELSE 0
        END)
    INTO absolute_earliness_score, relative_earliness_score, outcome_weighted_score, actionability_score
    FROM wallet_entries;
    
    -- Weighted composite
    final_score := (
        absolute_earliness_score * 0.25 +
        relative_earliness_score * 0.30 +
        outcome_weighted_score * 0.30 +
        actionability_score * 0.15
    );
    
    RETURN QUERY 
    SELECT 
        COALESCE(final_score, 0::DECIMAL(5,2)) as score,
        COALESCE((SELECT AVG(percentile_earliness) FROM wallet_entries), 0::DECIMAL(5,2)),
        COALESCE(outcome_weighted_score, 0::DECIMAL(5,2)),
        COALESCE((SELECT AVG(seconds_from_token_creation)::INTEGER FROM wallet_entries), 0),
        COALESCE(actionability_score, 0::DECIMAL(5,2));
END;
$function$

-- ---- calculate_hot_streak_score ----
CREATE OR REPLACE FUNCTION wallet_intel.calculate_hot_streak_score(p_wallet_address text, p_recent_days integer DEFAULT 3)
 RETURNS TABLE(score numeric, recent_expectancy numeric, recent_win_rate numeric, early_winner_rate numeric, streak_quality text)
 LANGUAGE plpgsql
AS $function$
DECLARE
    trade_count INTEGER;
    weighted_expectancy DECIMAL(10,4);
    win_rate_pct DECIMAL(5,2);
    early_win_pct DECIMAL(5,2);
    consistency_bonus DECIMAL(10,4);
    drawdown_penalty DECIMAL(10,4);
    luck_penalty DECIMAL(10,4);
    final_score DECIMAL(5,2);
    quality_label TEXT;
BEGIN
    WITH recent_trades AS (
        SELECT 
            wtp.realized_pnl_sol,
            wtp.realized_pnl_percent,
            wtp.closed_at,
            wt.percentile_earliness,
            ROW_NUMBER() OVER (ORDER BY wtp.closed_at DESC) as recency_rank,
            CASE WHEN wtp.realized_pnl_sol > 0 THEN 1 ELSE 0 END as is_win,
            CASE WHEN wtp.realized_pnl_percent > 100 THEN 1 ELSE 0 END as is_2x_plus
        FROM wallet_intel.wallet_token_positions wtp
        JOIN wallet_intel.wallet_trades wt 
            ON wtp.wallet_address = wt.wallet_address 
            AND wtp.token_address = wt.token_address
            AND wt.is_first_wallet_entry = true
        WHERE wtp.wallet_address = p_wallet_address
            AND wtp.is_closed = true
            AND wtp.closed_at > NOW() - (p_recent_days || ' days')::INTERVAL
    ),
    weighted_stats AS (
        SELECT 
            COUNT(*) as trades,
            -- Weighted expectancy (recent trades matter more)
            SUM(realized_pnl_sol * (1.0 / recency_rank)) / SUM(1.0 / recency_rank) as w_expectancy,
            AVG(is_win) * 100 as win_rate,
            AVG(CASE WHEN is_win = 1 AND percentile_earliness < 25 THEN 1 ELSE 0 END) * 100 as early_win_rate,
            -- Consistency: are recent trades clustered by outcome?
            STDDEV(realized_pnl_percent) as outcome_stddev,
            -- Max drawdown in period
            MIN(realized_pnl_percent) as worst_trade,
            -- Luck: concentration in 2x+ movers
            SUM(is_2x_plus)::DECIMAL / NULLIF(SUM(is_win), 0) as big_win_concentration
        FROM recent_trades
    )
    SELECT 
        trades,
        w_expectancy,
        win_rate,
        early_win_rate,
        outcome_stddev,
        worst_trade,
        big_win_concentration
    INTO trade_count, weighted_expectancy, win_rate_pct, early_win_pct, 
         consistency_bonus, drawdown_penalty, luck_penalty
    FROM weighted_stats;
    
    -- Insufficient sample
    IF trade_count < 5 THEN
        RETURN QUERY SELECT 
            0::DECIMAL(5,2), 0::DECIMAL(10,2), 0::DECIMAL(5,2), 0::DECIMAL(5,2), 'insufficient'::TEXT;
        RETURN;
    END IF;
    
    -- Base score from weighted expectancy
    final_score := LEAST(60, weighted_expectancy * 10);
    
    -- Bonuses
    final_score := final_score + (early_win_pct * 0.3); -- early winner bonus
    final_score := final_score + (win_rate_pct * 0.2); -- win rate bonus
    
    -- Penalties
    IF drawdown_penalty IS NOT NULL AND drawdown_penalty < -30 THEN
        final_score := final_score * 0.85; -- big loss penalty
    END IF;
    
    IF luck_penalty IS NOT NULL AND luck_penalty > 0.5 THEN
        final_score := final_score * 0.90; -- luck concentration penalty
    END IF;
    
    -- Cap and classify
    final_score := LEAST(100, final_score);
    
    quality_label := CASE 
        WHEN final_score >= 80 THEN 'elite'
        WHEN final_score >= 65 THEN 'strong'
        WHEN final_score >= 50 THEN 'decent'
        ELSE 'weak'
    END;
    
    RETURN QUERY SELECT 
        final_score,
        COALESCE(weighted_expectancy, 0::DECIMAL(10,2)),
        COALESCE(win_rate_pct, 0::DECIMAL(5,2)),
        COALESCE(early_win_pct, 0::DECIMAL(5,2)),
        quality_label;
END;
$function$

-- ---- calculate_performance_score ----
CREATE OR REPLACE FUNCTION wallet_intel.calculate_performance_score(p_wallet_address text, p_window_days integer DEFAULT 30)
 RETURNS TABLE(score numeric, realized_pnl_sol numeric, win_rate numeric, profit_factor numeric, expectancy numeric, sample_size integer, confidence_level text)
 LANGUAGE plpgsql
AS $function$
DECLARE
    total_pnl DECIMAL(20,8);
    total_wins DECIMAL(20,8);
    total_losses DECIMAL(20,8);
    trade_count INTEGER;
    winning_trades INTEGER;
    pnl_concentration DECIMAL(5,2); -- % PnL from top 3 trades
    base_score DECIMAL(10,4);
    reliability_penalty DECIMAL(10,4);
    concentration_penalty DECIMAL(10,4);
    final_score DECIMAL(5,2);
BEGIN
    -- Gather core stats
    SELECT 
        COALESCE(SUM(realized_pnl_sol), 0),
        COALESCE(SUM(CASE WHEN realized_pnl_sol > 0 THEN realized_pnl_sol ELSE 0 END), 0),
        COALESCE(ABS(SUM(CASE WHEN realized_pnl_sol < 0 THEN realized_pnl_sol ELSE 0 END)), 0.0001),
        COUNT(*),
        COUNT(*) FILTER (WHERE realized_pnl_sol > 0)
    INTO total_pnl, total_wins, total_losses, trade_count, winning_trades
    FROM wallet_intel.wallet_token_positions
    WHERE wallet_address = p_wallet_address
        AND is_closed = true
        AND closed_at > NOW() - (p_window_days || ' days')::INTERVAL;
    
    -- Check for insufficient data
    IF trade_count < 5 THEN
        RETURN QUERY SELECT 
            0::DECIMAL(5,2) as score,
            total_pnl,
            0::DECIMAL(5,2) as win_rate,
            0::DECIMAL(10,2) as profit_factor,
            0::DECIMAL(10,2) as expectancy,
            trade_count,
            'insufficient'::TEXT;
        RETURN;
    END IF;
    
    -- Calculate PnL concentration (top 3 trades)
    WITH ranked_trades AS (
        SELECT realized_pnl_sol,
               ROW_NUMBER() OVER (ORDER BY realized_pnl_sol DESC) as rank
        FROM wallet_intel.wallet_token_positions
        WHERE wallet_address = p_wallet_address
            AND is_closed = true
            AND closed_at > NOW() - (p_window_days || ' days')::INTERVAL
    )
    SELECT 
        CASE WHEN total_pnl > 0 
            THEN (SUM(realized_pnl_sol) / total_pnl * 100)
            ELSE 0 
        END
    INTO pnl_concentration
    FROM ranked_trades
    WHERE rank <= 3;
    
    -- Base score: normalized PnL with profit factor weighting
    -- PnL in SOL normalized to 0-100 scale (100 SOL = max)
    base_score := LEAST(100, (total_pnl / 100.0) * 50);
    
    -- Add profit factor component (0-50 points)
    base_score := base_score + LEAST(50, (total_wins / NULLIF(total_losses, 0)) * 10);
    
    -- Reliability penalty: reduce score if sample size is small
    reliability_penalty := CASE 
        WHEN trade_count >= 50 THEN 1.0
        WHEN trade_count >= 30 THEN 0.95
        WHEN trade_count >= 20 THEN 0.90
        WHEN trade_count >= 10 THEN 0.85
        ELSE 0.75
    END;
    
    -- Concentration penalty: reduce score if PnL is from few lucky trades
    concentration_penalty := CASE 
        WHEN pnl_concentration > 80 THEN 0.70 -- 80%+ from top 3 = very concentrated
        WHEN pnl_concentration > 60 THEN 0.85
        WHEN pnl_concentration > 40 THEN 0.95
        ELSE 1.0
    END;
    
    -- Final score
    final_score := LEAST(100, base_score * reliability_penalty * concentration_penalty);
    
    RETURN QUERY SELECT 
        final_score,
        total_pnl,
        ROUND((winning_trades::DECIMAL / NULLIF(trade_count, 0)) * 100, 2) as win_rate,
        ROUND(total_wins / NULLIF(total_losses, 0), 2) as profit_factor,
        ROUND(total_pnl / NULLIF(trade_count, 0), 2) as expectancy,
        trade_count,
        CASE 
            WHEN trade_count >= 50 THEN 'high'
            WHEN trade_count >= 20 THEN 'medium'
            ELSE 'low'
        END::TEXT as confidence_level;
END;
$function$

-- ---- calculate_predictive_score ----
CREATE OR REPLACE FUNCTION wallet_intel.calculate_predictive_score(p_wallet_address text, p_window_days integer DEFAULT 30)
 RETURNS TABLE(score numeric, forward_return_5m numeric, forward_return_1h numeric, forward_return_24h numeric, cohort_activation_score numeric, propagation_score numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    avg_forward_5m DECIMAL(10,2);
    avg_forward_1h DECIMAL(10,2);
    avg_forward_24h DECIMAL(10,2);
    follow_through_score DECIMAL(10,4);
    cohort_score DECIMAL(10,4);
    final_score DECIMAL(5,2);
BEGIN
    -- Calculate forward returns after wallet entry
    WITH wallet_buys AS (
        SELECT 
            wt.token_address,
            wt.block_time,
            wt.price_per_token,
            
            -- Forward price snapshots (would come from token_market_snapshots)
            (SELECT price_usd FROM wallet_intel.token_market_snapshots tms
             WHERE tms.token_address = wt.token_address
             AND tms.snapshot_time >= wt.block_time + INTERVAL '5 minutes'
             ORDER BY tms.snapshot_time LIMIT 1) as price_5m_after,
             
            (SELECT price_usd FROM wallet_intel.token_market_snapshots tms
             WHERE tms.token_address = wt.token_address
             AND tms.snapshot_time >= wt.block_time + INTERVAL '1 hour'
             ORDER BY tms.snapshot_time LIMIT 1) as price_1h_after,
             
            (SELECT price_usd FROM wallet_intel.token_market_snapshots tms
             WHERE tms.token_address = wt.token_address
             AND tms.snapshot_time >= wt.block_time + INTERVAL '24 hours'
             ORDER BY tms.snapshot_time LIMIT 1) as price_24h_after,
             
            -- Count of other strong wallets that followed
            (SELECT COUNT(DISTINCT wallet_address)
             FROM wallet_intel.wallet_trades wt2
             WHERE wt2.token_address = wt.token_address
             AND wt2.block_time BETWEEN wt.block_time AND wt.block_time + INTERVAL '15 minutes'
             AND wt2.wallet_address != wt.wallet_address
             AND wt2.action = 'buy') as follower_count
             
        FROM wallet_intel.wallet_trades wt
        WHERE wt.wallet_address = p_wallet_address
            AND wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time > NOW() - (p_window_days || ' days')::INTERVAL
    )
    SELECT 
        AVG(((price_5m_after - price_per_token) / NULLIF(price_per_token, 0)) * 100),
        AVG(((price_1h_after - price_per_token) / NULLIF(price_per_token, 0)) * 100),
        AVG(((price_24h_after - price_per_token) / NULLIF(price_per_token, 0)) * 100),
        AVG(CASE WHEN follower_count >= 5 THEN 100 WHEN follower_count >= 3 THEN 75 WHEN follower_count >= 1 THEN 50 ELSE 0 END)
    INTO avg_forward_5m, avg_forward_1h, avg_forward_24h, follow_through_score
    FROM wallet_buys;
    
    -- Score based on forward returns (weighted by timeframe)
    final_score := LEAST(100, (
        GREATEST(0, COALESCE(avg_forward_5m, 0)) * 0.15 +
        GREATEST(0, COALESCE(avg_forward_1h, 0)) * 0.40 +
        GREATEST(0, COALESCE(avg_forward_24h, 0)) * 0.25 +
        COALESCE(follow_through_score, 0) * 0.20
    ));
    
    RETURN QUERY SELECT 
        COALESCE(final_score, 0::DECIMAL(5,2)),
        COALESCE(avg_forward_5m, 0::DECIMAL(10,2)),
        COALESCE(avg_forward_1h, 0::DECIMAL(10,2)),
        COALESCE(avg_forward_24h, 0::DECIMAL(10,2)),
        COALESCE(follow_through_score, 0::DECIMAL(5,2)),
        COALESCE(follow_through_score, 0::DECIMAL(5,2)); -- propagation = cohort for now
END;
$function$

-- ---- calculate_trust_score ----
CREATE OR REPLACE FUNCTION wallet_intel.calculate_trust_score(p_wallet_address text, p_window_days integer DEFAULT 30)
 RETURNS TABLE(score numeric, confidence_level text, manipulation_risk text, sample_size integer, pnl_concentration numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    trade_count INTEGER;
    token_diversity INTEGER;
    pnl_top3_concentration DECIMAL(5,2);
    microcap_rug_exposure DECIMAL(5,2);
    wash_like_score DECIMAL(5,2);
    creator_adjacency DECIMAL(5,2);
    base_trust DECIMAL(10,4);
    sample_penalty DECIMAL(10,4);
    concentration_penalty DECIMAL(10,4);
    manipulation_penalty DECIMAL(10,4);
    final_score DECIMAL(5,2);
    confidence_label TEXT;
    risk_label TEXT;
BEGIN
    -- Gather stats
    WITH position_stats AS (
        SELECT 
            COUNT(DISTINCT token_address) as unique_tokens,
            COUNT(*) as total_positions,
            SUM(CASE WHEN became_illiquid_trap THEN 1 ELSE 0 END)::DECIMAL / NULLIF(COUNT(*), 0) * 100 as rug_rate
        FROM wallet_intel.wallet_token_positions
        WHERE wallet_address = p_wallet_address
            AND is_closed = true
            AND closed_at > NOW() - (p_window_days || ' days')::INTERVAL
    ),
    pnl_concentration AS (
        SELECT 
            (SUM(realized_pnl_sol) FILTER (WHERE rank <= 3) / NULLIF(SUM(realized_pnl_sol), 0) * 100) as top3_pct
        FROM (
            SELECT realized_pnl_sol, ROW_NUMBER() OVER (ORDER BY realized_pnl_sol DESC) as rank
            FROM wallet_intel.wallet_token_positions
            WHERE wallet_address = p_wallet_address
                AND is_closed = true
                AND realized_pnl_sol > 0
                AND closed_at > NOW() - (p_window_days || ' days')::INTERVAL
        ) ranked
    )
    SELECT 
        ps.total_positions,
        ps.unique_tokens,
        COALESCE(pc.top3_pct, 0),
        COALESCE(ps.rug_rate, 0)
    INTO trade_count, token_diversity, pnl_top3_concentration, microcap_rug_exposure
    FROM position_stats ps
    CROSS JOIN pnl_concentration pc;
    
    -- Get manipulation indicators from behavior profile
    SELECT 
        COALESCE(manipulation_suspicion_score, 0),
        COALESCE(token_creator_adjacency_score, 0)
    INTO wash_like_score, creator_adjacency
    FROM wallet_intel.wallet_behavior_profiles
    WHERE wallet_address = p_wallet_address;
    
    -- Base trust from sample size
    base_trust := 100;
    
    -- Sample size penalty
    sample_penalty := CASE 
        WHEN trade_count >= 50 THEN 1.0
        WHEN trade_count >= 30 THEN 0.95
        WHEN trade_count >= 20 THEN 0.90
        WHEN trade_count >= 10 THEN 0.80
        ELSE 0.60
    END;
    
    -- Concentration penalty (high luck concentration = lower trust)
    concentration_penalty := CASE 
        WHEN pnl_top3_concentration > 80 THEN 0.70
        WHEN pnl_top3_concentration > 60 THEN 0.85
        WHEN pnl_top3_concentration > 40 THEN 0.95
        ELSE 1.0
    END;
    
    -- Manipulation penalty
    manipulation_penalty := (100 - wash_like_score - creator_adjacency - microcap_rug_exposure) / 100.0;
    manipulation_penalty := GREATEST(0.5, manipulation_penalty); -- floor at 0.5
    
    -- Final score
    final_score := base_trust * sample_penalty * concentration_penalty * manipulation_penalty;
    
    -- Labels
    confidence_label := CASE 
        WHEN trade_count >= 50 THEN 'high'
        WHEN trade_count >= 20 THEN 'medium'
        ELSE 'low'
    END;
    
    risk_label := CASE 
        WHEN manipulation_penalty < 0.7 THEN 'high'
        WHEN manipulation_penalty < 0.85 THEN 'medium'
        ELSE 'low'
    END;
    
    RETURN QUERY SELECT 
        final_score,
        confidence_label,
        risk_label,
        trade_count,
        pnl_top3_concentration;
END;
$function$

-- ---- detect_cohort_activation ----
CREATE OR REPLACE FUNCTION wallet_intel.detect_cohort_activation(p_lookback_minutes integer DEFAULT 15, p_min_wallets integer DEFAULT 3)
 RETURNS TABLE(token_address text, token_symbol text, wallet_count integer, total_volume_sol numeric, avg_hot_streak_score numeric, earliest_entry timestamp with time zone, latest_entry timestamp with time zone, signal_strength text)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH recent_entries AS (
        SELECT 
            wt.token_address,
            wt.token_symbol,
            wt.wallet_address,
            wt.amount_sol,
            wt.block_time,
            (SELECT score FROM wallet_intel.calculate_hot_streak_score(wt.wallet_address, 3)) as hot_score
        FROM wallet_intel.wallet_trades wt
        WHERE wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time > NOW() - (p_lookback_minutes || ' minutes')::INTERVAL
    ),
    cohort_stats AS (
        SELECT 
            re.token_address,
            re.token_symbol,
            COUNT(DISTINCT re.wallet_address) as wallet_cnt,
            SUM(re.amount_sol) as total_vol,
            AVG(re.hot_score) as avg_hot,
            MIN(re.block_time) as first_entry,
            MAX(re.block_time) as last_entry
        FROM recent_entries re
        WHERE re.hot_score >= 50 -- Only count hot wallets
        GROUP BY re.token_address, re.token_symbol
        HAVING COUNT(DISTINCT re.wallet_address) >= p_min_wallets
    )
    SELECT 
        cs.token_address,
        cs.token_symbol,
        cs.wallet_cnt,
        cs.total_vol,
        cs.avg_hot,
        cs.first_entry,
        cs.last_entry,
        CASE 
            WHEN cs.wallet_cnt >= 5 AND cs.avg_hot >= 70 THEN 'STRONG'
            WHEN cs.wallet_cnt >= 3 AND cs.avg_hot >= 60 THEN 'MEDIUM'
            ELSE 'WEAK'
        END as signal_strength
    FROM cohort_stats cs
    ORDER BY (cs.wallet_cnt * cs.avg_hot) DESC;
END;
$function$

