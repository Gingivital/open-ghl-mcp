-- ---- analyze_signal_performance ----
CREATE OR REPLACE FUNCTION wallet_intel.analyze_signal_performance(p_signal_type text DEFAULT NULL::text, p_days_back integer DEFAULT 7)
 RETURNS TABLE(signal_type text, total_signals integer, executed_count integer, execution_rate numeric, avg_outcome_1h numeric, avg_outcome_24h numeric, win_rate_1h numeric, win_rate_24h numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    SELECT 
        sl.signal_type,
        COUNT(*)::INTEGER as total_signals,
        COUNT(*) FILTER (WHERE sl.was_executed)::INTEGER as executed_count,
        ROUND((COUNT(*) FILTER (WHERE sl.was_executed)::DECIMAL / NULLIF(COUNT(*), 0)) * 100, 2) as execution_rate,
        ROUND(AVG(sl.outcome_1h), 2) as avg_outcome_1h,
        ROUND(AVG(sl.outcome_24h), 2) as avg_outcome_24h,
        ROUND((COUNT(*) FILTER (WHERE sl.outcome_1h > 0)::DECIMAL / NULLIF(COUNT(*), 0)) * 100, 2) as win_rate_1h,
        ROUND((COUNT(*) FILTER (WHERE sl.outcome_24h > 0)::DECIMAL / NULLIF(COUNT(*), 0)) * 100, 2) as win_rate_24h
    FROM wallet_intel.signal_log sl
    WHERE sl.generated_at > NOW() - (p_days_back || ' days')::INTERVAL
        AND (p_signal_type IS NULL OR sl.signal_type = p_signal_type)
        AND sl.outcome_1h IS NOT NULL
    GROUP BY sl.signal_type
    ORDER BY avg_outcome_24h DESC;
END;
$function$

-- ---- auto_score_on_trade ----
CREATE OR REPLACE FUNCTION wallet_intel.auto_score_on_trade()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    last_score_time TIMESTAMPTZ;
    should_score BOOLEAN := false;
BEGIN
    -- Check when wallet was last scored
    SELECT MAX(scored_at) INTO last_score_time
    FROM wallet_intel.wallet_score_history
    WHERE wallet_address = NEW.wallet_address;
    
    -- Score if:
    -- 1. Never scored before, OR
    -- 2. More than 1 hour since last score, OR
    -- 3. This is a buy trade (more important than sells)
    should_score := (
        last_score_time IS NULL OR
        last_score_time < NOW() - INTERVAL '1 hour' OR
        NEW.action = 'buy'
    );
    
    IF should_score THEN
        -- Calculate and store scores
        INSERT INTO wallet_intel.wallet_score_history (
            wallet_address,
            scored_at,
            performance_score,
            earliness_score,
            predictive_score,
            consistency_score,
            trust_score,
            hot_streak_score,
            sample_size
        )
        SELECT 
            wallet_address,
            calculated_at,
            performance_score,
            earliness_score,
            predictive_score,
            consistency_score,
            trust_score,
            hot_streak_score,
            (SELECT COUNT(*) FROM wallet_intel.wallet_token_positions 
             WHERE wallet_address = NEW.wallet_address AND is_closed = true) as sample_size
        FROM wallet_intel.calculate_all_scores(NEW.wallet_address, 30);
    END IF;
    
    RETURN NEW;
END;
$function$

-- ---- backtest_cohort_strategy ----
CREATE OR REPLACE FUNCTION wallet_intel.backtest_cohort_strategy(p_start_date timestamp with time zone, p_end_date timestamp with time zone, p_min_cohort_size integer DEFAULT 3, p_time_window_minutes integer DEFAULT 15)
 RETURNS TABLE(total_cohort_signals integer, avg_cohort_size numeric, win_rate numeric, avg_return_24h numeric, best_return numeric, worst_return numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH windowed_entries AS (
        SELECT 
            wt.token_address,
            wt.wallet_address,
            wt.block_time,
            wt.price_per_token,
            -- Window function to count wallets entering within time window
            COUNT(DISTINCT wt.wallet_address) OVER (
                PARTITION BY wt.token_address 
                ORDER BY wt.block_time 
                RANGE BETWEEN CURRENT ROW AND INTERVAL '1 minute' * p_time_window_minutes FOLLOWING
            ) as cohort_count
        FROM wallet_intel.wallet_trades wt
        WHERE wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time BETWEEN p_start_date AND p_end_date
    ),
    cohort_signals AS (
        SELECT DISTINCT ON (we.token_address)
            we.token_address,
            we.block_time as signal_time,
            we.price_per_token as entry_price,
            we.cohort_count,
            -- Outcome: price 24h later
            (SELECT 
                ((tms.price_usd - we.price_per_token) / NULLIF(we.price_per_token, 0)) * 100
             FROM wallet_intel.token_market_snapshots tms
             WHERE tms.token_address = we.token_address
                 AND tms.snapshot_time >= we.block_time + INTERVAL '24 hours'
             ORDER BY tms.snapshot_time LIMIT 1
            ) as return_24h
        FROM windowed_entries we
        WHERE we.cohort_count >= p_min_cohort_size
        ORDER BY we.token_address, we.block_time
    )
    SELECT 
        COUNT(*)::INTEGER,
        ROUND(AVG(cohort_count), 1),
        ROUND((COUNT(*) FILTER (WHERE return_24h > 0)::DECIMAL / NULLIF(COUNT(*), 0)) * 100, 2),
        ROUND(AVG(return_24h), 2),
        ROUND(MAX(return_24h), 2),
        ROUND(MIN(return_24h), 2)
    FROM cohort_signals
    WHERE return_24h IS NOT NULL;
END;
$function$

-- ---- backtest_optimal_wallets ----
CREATE OR REPLACE FUNCTION wallet_intel.backtest_optimal_wallets(p_start_date timestamp with time zone, p_end_date timestamp with time zone, p_min_trades integer DEFAULT 10)
 RETURNS TABLE(wallet_address text, total_trades integer, win_rate numeric, avg_return numeric, total_pnl_estimate numeric, profit_factor numeric, max_winner numeric, max_loser numeric, consistency_score numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH wallet_performance AS (
        SELECT 
            wt.wallet_address,
            COUNT(*) as trade_count,
            COUNT(*) FILTER (WHERE wtp.realized_pnl_percent > 0) as winners,
            AVG(wtp.realized_pnl_percent) as avg_pnl_pct,
            SUM(wtp.realized_pnl_percent) as total_pnl_pct,
            SUM(CASE WHEN wtp.realized_pnl_percent > 0 THEN wtp.realized_pnl_percent ELSE 0 END) as total_wins,
            ABS(SUM(CASE WHEN wtp.realized_pnl_percent < 0 THEN wtp.realized_pnl_percent ELSE 0 END)) as total_losses,
            MAX(wtp.realized_pnl_percent) as best_trade,
            MIN(wtp.realized_pnl_percent) as worst_trade,
            STDDEV(wtp.realized_pnl_percent) as pnl_stddev
        FROM wallet_intel.wallet_trades wt
        JOIN wallet_intel.wallet_token_positions wtp 
            ON wt.wallet_address = wtp.wallet_address 
            AND wt.token_address = wtp.token_address
        WHERE wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time BETWEEN p_start_date AND p_end_date
            AND wtp.is_closed = true
            AND wtp.realized_pnl_percent IS NOT NULL
        GROUP BY wt.wallet_address
        HAVING COUNT(*) >= p_min_trades
    )
    SELECT 
        wp.wallet_address,
        wp.trade_count::INTEGER,
        ROUND((wp.winners::DECIMAL / NULLIF(wp.trade_count, 0)) * 100, 2),
        ROUND(wp.avg_pnl_pct, 2),
        ROUND(wp.total_pnl_pct, 2),
        ROUND(wp.total_wins / NULLIF(wp.total_losses, 0.01), 2),
        ROUND(wp.best_trade, 2),
        ROUND(wp.worst_trade, 2),
        -- Consistency: high avg return with low volatility = good
        ROUND(CASE WHEN wp.pnl_stddev > 0 THEN wp.avg_pnl_pct / wp.pnl_stddev ELSE 0 END, 4)
    FROM wallet_performance wp
    ORDER BY (wp.avg_pnl_pct * (wp.winners::DECIMAL / wp.trade_count)) DESC
    LIMIT 50;
END;
$function$

-- ---- backtest_score_threshold ----
CREATE OR REPLACE FUNCTION wallet_intel.backtest_score_threshold(p_start_date timestamp with time zone, p_end_date timestamp with time zone, p_min_hot_streak integer DEFAULT 70, p_min_trust integer DEFAULT 60, p_position_size_sol numeric DEFAULT 0.5)
 RETURNS TABLE(strategy_name text, total_signals integer, trades_taken integer, win_rate numeric, avg_return_percent numeric, total_pnl_sol numeric, profit_factor numeric)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH historical_signals AS (
        -- Simulate signals that would have been generated
        SELECT 
            wt.wallet_address,
            wt.token_address,
            wt.block_time,
            wt.price_per_token as entry_price,
            (SELECT score FROM wallet_intel.calculate_hot_streak_score(wt.wallet_address, 3)) as hot_score,
            (SELECT score FROM wallet_intel.calculate_trust_score(wt.wallet_address, 30)) as trust_score,
            wtp.realized_pnl_percent
        FROM wallet_intel.wallet_trades wt
        LEFT JOIN wallet_intel.wallet_token_positions wtp 
            ON wt.wallet_address = wtp.wallet_address 
            AND wt.token_address = wtp.token_address
        WHERE wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time BETWEEN p_start_date AND p_end_date
    ),
    qualified_signals AS (
        SELECT *
        FROM historical_signals
        WHERE hot_score >= p_min_hot_streak
            AND trust_score >= p_min_trust
            AND realized_pnl_percent IS NOT NULL
    )
    SELECT 
        'Score Threshold: ' || p_min_hot_streak || '/' || p_min_trust as strategy_name,
        (SELECT COUNT(*) FROM historical_signals)::INTEGER,
        COUNT(*)::INTEGER as trades_taken,
        ROUND((COUNT(*) FILTER (WHERE realized_pnl_percent > 0)::DECIMAL / NULLIF(COUNT(*), 0)) * 100, 2),
        ROUND(AVG(realized_pnl_percent), 2),
        ROUND(SUM(realized_pnl_percent / 100 * p_position_size_sol), 4),
        ROUND(
            SUM(CASE WHEN realized_pnl_percent > 0 THEN realized_pnl_percent ELSE 0 END) /
            NULLIF(ABS(SUM(CASE WHEN realized_pnl_percent < 0 THEN realized_pnl_percent ELSE 0 END)), 0.01),
            2
        )
    FROM qualified_signals;
END;
$function$

-- ---- backtest_wallet_follow ----
CREATE OR REPLACE FUNCTION wallet_intel.backtest_wallet_follow(p_wallet_addresses text[], p_start_date timestamp with time zone, p_end_date timestamp with time zone, p_position_size_sol numeric DEFAULT 1.0, p_max_slippage_percent numeric DEFAULT 3.0)
 RETURNS TABLE(total_trades integer, winning_trades integer, losing_trades integer, win_rate numeric, total_pnl_sol numeric, avg_pnl_per_trade numeric, profit_factor numeric, max_drawdown_percent numeric, sharpe_ratio numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    simulated_trades RECORD;
    total_cost DECIMAL := 0;
    total_revenue DECIMAL := 0;
    trade_count INTEGER := 0;
    winner_count INTEGER := 0;
    loser_count INTEGER := 0;
    total_wins DECIMAL := 0;
    total_losses DECIMAL := 0;
    cumulative_pnl DECIMAL := 0;
    peak_pnl DECIMAL := 0;
    max_dd DECIMAL := 0;
    returns_array DECIMAL[];
BEGIN
    -- Simulate following wallet trades
    FOR simulated_trades IN
        SELECT 
            wt.wallet_address,
            wt.token_address,
            wt.block_time as entry_time,
            wt.price_per_token as entry_price,
            wt.amount_sol,
            wt.token_liquidity_at_trade,
            -- Exit: use actual position exit or 24h later
            COALESCE(wtp.realized_pnl_percent, 
                     ((
                         SELECT price_usd FROM wallet_intel.token_market_snapshots tms
                         WHERE tms.token_address = wt.token_address
                             AND tms.snapshot_time >= wt.block_time + INTERVAL '24 hours'
                         ORDER BY tms.snapshot_time LIMIT 1
                     ) - wt.price_per_token) / NULLIF(wt.price_per_token, 0) * 100
            ) as pnl_percent
        FROM wallet_intel.wallet_trades wt
        LEFT JOIN wallet_intel.wallet_token_positions wtp 
            ON wt.wallet_address = wtp.wallet_address 
            AND wt.token_address = wtp.token_address
        WHERE wt.wallet_address = ANY(p_wallet_addresses)
            AND wt.action = 'buy'
            AND wt.is_first_wallet_entry = true
            AND wt.block_time BETWEEN p_start_date AND p_end_date
            AND wt.token_liquidity_at_trade >= (p_position_size_sol * 240 / 0.02) -- 2% liquidity check
        ORDER BY wt.block_time
    LOOP
        trade_count := trade_count + 1;
        
        -- Apply slippage
        IF simulated_trades.pnl_percent IS NOT NULL THEN
            DECLARE
                adjusted_pnl DECIMAL;
            BEGIN
                adjusted_pnl := simulated_trades.pnl_percent - p_max_slippage_percent;
                
                total_cost := total_cost + p_position_size_sol;
                total_revenue := total_revenue + (p_position_size_sol * (1 + adjusted_pnl / 100));
                
                IF adjusted_pnl > 0 THEN
                    winner_count := winner_count + 1;
                    total_wins := total_wins + (p_position_size_sol * adjusted_pnl / 100);
                ELSE
                    loser_count := loser_count + 1;
                    total_losses := total_losses + ABS(p_position_size_sol * adjusted_pnl / 100);
                END IF;
                
                -- Track drawdown
                cumulative_pnl := total_revenue - total_cost;
                IF cumulative_pnl > peak_pnl THEN
                    peak_pnl := cumulative_pnl;
                END IF;
                
                IF peak_pnl > 0 THEN
                    DECLARE
                        current_dd DECIMAL;
                    BEGIN
                        current_dd := ((peak_pnl - cumulative_pnl) / peak_pnl) * 100;
                        IF current_dd > max_dd THEN
                            max_dd := current_dd;
                        END IF;
                    END;
                END IF;
                
                -- Store returns for Sharpe calculation
                returns_array := array_append(returns_array, adjusted_pnl);
            END;
        END IF;
    END LOOP;
    
    -- Calculate Sharpe (simplified: avg return / stddev return)
    DECLARE
        avg_return DECIMAL;
        stddev_return DECIMAL;
        sharpe DECIMAL;
    BEGIN
        IF array_length(returns_array, 1) > 1 THEN
            SELECT AVG(val), STDDEV(val) INTO avg_return, stddev_return
            FROM unnest(returns_array) as val;
            
            sharpe := CASE WHEN stddev_return > 0 THEN avg_return / stddev_return ELSE 0 END;
        ELSE
            sharpe := 0;
        END IF;
        
        RETURN QUERY SELECT 
            trade_count,
            winner_count,
            loser_count,
            ROUND((winner_count::DECIMAL / NULLIF(trade_count, 0)) * 100, 2),
            ROUND(total_revenue - total_cost, 4),
            ROUND((total_revenue - total_cost) / NULLIF(trade_count, 0), 4),
            ROUND(total_wins / NULLIF(total_losses, 0.0001), 2),
            ROUND(max_dd, 2),
            ROUND(sharpe, 4);
    END;
END;
$function$

-- ---- bulk_ingest_trades ----
CREATE OR REPLACE FUNCTION wallet_intel.bulk_ingest_trades(p_trades jsonb)
 RETURNS TABLE(inserted integer, updated integer, errors integer)
 LANGUAGE plpgsql
AS $function$
DECLARE
    trade JSONB;
    inserted_count INTEGER := 0;
    updated_count INTEGER := 0;
    error_count INTEGER := 0;
    trade_id BIGINT;
BEGIN
    FOR trade IN SELECT * FROM jsonb_array_elements(p_trades)
    LOOP
        BEGIN
            SELECT wallet_intel.ingest_wallet_trade(
                trade->>'wallet_address',
                trade->>'signature',
                (trade->>'block_time')::TIMESTAMPTZ,
                (trade->>'block_slot')::BIGINT,
                trade->>'token_address',
                trade->>'token_symbol',
                trade->>'token_name',
                trade->>'action',
                (trade->>'amount_tokens')::DECIMAL,
                (trade->>'amount_sol')::DECIMAL,
                (trade->>'price_per_token')::DECIMAL,
                (trade->>'token_mcap')::DECIMAL,
                (trade->>'token_liquidity')::DECIMAL,
                (trade->>'slippage_percent')::DECIMAL,
                (trade->>'fees_paid_sol')::DECIMAL
            ) INTO trade_id;
            
            IF trade_id IS NOT NULL THEN
                inserted_count := inserted_count + 1;
            END IF;
        EXCEPTION
            WHEN OTHERS THEN
                error_count := error_count + 1;
                RAISE NOTICE 'Error ingesting trade: %', SQLERRM;
        END;
    END LOOP;
    
    RETURN QUERY SELECT inserted_count, updated_count, error_count;
END;
$function$

-- ---- calculate_all_scores ----
CREATE OR REPLACE FUNCTION wallet_intel.calculate_all_scores(p_wallet_address text, p_window_days integer DEFAULT 30)
 RETURNS TABLE(wallet_address text, calculated_at timestamp with time zone, performance_score numeric, earliness_score numeric, predictive_score numeric, consistency_score numeric, trust_score numeric, hot_streak_score numeric, overall_score numeric)
 LANGUAGE plpgsql
AS $function$
DECLARE
    perf_score DECIMAL(5,2);
    early_score DECIMAL(5,2);
    pred_score DECIMAL(5,2);
    cons_score DECIMAL(5,2);
    trust_sc DECIMAL(5,2);
    streak_score DECIMAL(5,2);
    composite DECIMAL(5,2);
BEGIN
    -- Calculate individual dimensions
    SELECT score INTO perf_score FROM wallet_intel.calculate_performance_score(p_wallet_address, p_window_days);
    SELECT score INTO early_score FROM wallet_intel.calculate_earliness_score(p_wallet_address, p_window_days);
    SELECT score INTO pred_score FROM wallet_intel.calculate_predictive_score(p_wallet_address, p_window_days);
    SELECT score INTO trust_sc FROM wallet_intel.calculate_trust_score(p_wallet_address, p_window_days);
    SELECT score INTO streak_score FROM wallet_intel.calculate_hot_streak_score(p_wallet_address, 3);
    
    -- Consistency from rolling stats (if available)
    SELECT COALESCE(AVG(sharpe_like_score) * 10, 50) INTO cons_score
    FROM wallet_intel.wallet_rolling_stats
    WHERE wallet_address = p_wallet_address
        AND window_period = '7d'
        AND calculated_at > NOW() - INTERVAL '7 days';
    
    -- Composite (weighted)
    composite := (
        COALESCE(perf_score, 0) * 0.25 +
        COALESCE(early_score, 0) * 0.20 +
        COALESCE(pred_score, 0) * 0.25 +
        COALESCE(cons_score, 0) * 0.10 +
        COALESCE(trust_sc, 0) * 0.10 +
        COALESCE(streak_score, 0) * 0.10
    );
    
    RETURN QUERY SELECT 
        p_wallet_address,
        NOW(),
        COALESCE(perf_score, 0::DECIMAL(5,2)),
        COALESCE(early_score, 0::DECIMAL(5,2)),
        COALESCE(pred_score, 0::DECIMAL(5,2)),
        COALESCE(cons_score, 0::DECIMAL(5,2)),
        COALESCE(trust_sc, 0::DECIMAL(5,2)),
        COALESCE(streak_score, 0::DECIMAL(5,2)),
        composite;
END;
$function$

